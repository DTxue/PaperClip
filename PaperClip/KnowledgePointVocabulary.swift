            let pts = points(for: s.rawValue)
            guard !pts.isEmpty else { return nil }
            // 每科取前 30 个最核心词汇，避免 prompt 过长
            let sample = pts.prefix(30).joined(separator: "、")
            return "\(s.rawValue)：\(sample)"
        }.joined(separator: "\n")
    }

